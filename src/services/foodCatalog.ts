export function lookupFoodByQuery(query: string): FoodCatalogEntry[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return FOOD_DATABASE.slice(0, 15);

  return FOOD_DATABASE.filter(f => {
    if (f.name.toLowerCase().includes(clean)) return true;
    return f.aliases.some(alias => alias.includes(clean) || clean.includes(alias));
  });
}

export function convertEntryToNutritionItem(entry: FoodCatalogEntry, portionGrams?: number): FoodItemNutrition {
  const grams = portionGrams ?? entry.defaultPortionGrams;
  const ratio = grams / 100;

  return {
    id: `food-${Date.now()}-${Math.random().toString(36).substr(2, 6)}`,
    name: entry.name,
    portionGrams: Math.round(grams),
    portionDescription: entry.portionDescription || `${grams}g`,
    calories: Math.round(entry.caloriesPer100g * ratio),
    protein: Number((entry.proteinPer100g * ratio).toFixed(1)),
    carbs: Number((entry.carbsPer100g * ratio).toFixed(1)),
    fat: Number((entry.fatPer100g * ratio).toFixed(1)),
    fiber: Number((entry.fiberPer100g * ratio).toFixed(1)),
    sugar: Number((entry.sugarPer100g * ratio).toFixed(1)),
    sodium: Math.round(entry.sodiumPer100g * ratio),
    category: entry.category,
    confidence: 0.96,
  };
}

